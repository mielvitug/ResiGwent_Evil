// collage can show every art file, not just catalog-referenced ones.
// Runs via the predev/prebuild hooks; rerun manually after adding art:
//   node scripts/generate-menu-art.js
import { readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const cardsDir = join(root, 'public', 'images', 'cards')
const outFile = join(root, 'src', 'data', 'menuArtManifest.js')
const imageExtensions = new Set(['.png', '.webp', '.jpg', '.jpeg', '.avif'])

const files = readdirSync(cardsDir, { withFileTypes: true })
  .filter((entry) => entry.isFile())
  .map((entry) => entry.name)
  .filter((name) => {
    const dot = name.lastIndexOf('.')
    return dot > 0 && imageExtensions.has(name.slice(dot).toLowerCase())
  })
  .sort((a, b) => a.localeCompare(b, 'en'))

writeFileSync(
  outFile,
  `// AUTO-GENERATED by scripts/generate-menu-art.js — do not edit by hand.\n// Reruns on every \`npm run dev\` / \`npm run build\` via predev/prebuild.\nexport const menuArtwork = ${JSON.stringify(files, null, 2)}\n`,
)

console.log(`menu art manifest: ${files.length} files -> src/data/menuArtManifest.js`)
